  it("accepts Standard Webhooks signatures made with the source secret and dedupes by message id", async () => {
    await create();
    // What a Standard Webhooks sender does with the secret: base64-decode what follows `whsec_` and sign with it.
    const key = Buffer.from(secret.slice("whsec_".length), "base64");
    expect(key.toString("base64")).toBe(secret.slice("whsec_".length));
    const now = () => Math.floor(Date.now() / 1000);
    const signed = (raw: string, id: string, { at = now(), names = "webhook", with: k = key } = {}) => ({
      payload: raw,
      headers: {
        "content-type": "application/json",
        [`${names}-id`]: id,
        [`${names}-timestamp`]: String(at),
        [`${names}-signature`]: `v1,${createHmac("sha256", k).update(`${id}.${at}.${raw}`).digest("base64")}`,
      },
    });
    const url = `/api/hook-sources/${sourceId}`;
    const raw = '{"type":"deploy.finished"}';
    const first = await w.webhooks("POST", url, signed(raw, "msg_1"));
    expect(first.status, first.raw).toBe(202);
    // The sender retries a message under the same id.
    const retry = await w.webhooks("POST", url, signed(raw, "msg_1"));
    expect(retry.status).toBe(200);
    expect(retry.body.id).toBe(first.body.id);
    // The signature covers the id, not an Idempotency-Key, so a replay under a new key is the same message.
    const replay = signed(raw, "msg_1");
    replay.headers["idempotency-key"] = "replayed";
    expect((await w.webhooks("POST", url, replay)).status).toBe(200);
    expect((await w.webhooks("POST", url, signed(raw, "msg_2", { names: "svix" }))).status).toBe(202);
    // While the sender rotates keys it lists several signatures; one that verifies is enough.
    const rotating = signed(raw, "msg_3");
    rotating.headers["webhook-signature"] =
      `v1,${Buffer.alloc(32).toString("base64")} ${rotating.headers["webhook-signature"]}`;
    expect((await w.webhooks("POST", url, rotating)).status).toBe(202);
    const tampered = { ...signed(raw, "msg_4"), payload: '{"type":"other"}' };
    for (const bad of [
      tampered,
      signed(raw, "msg_5", { with: Buffer.from("another key") }),
      signed(raw, "msg_6", { at: now() - 6 * 60 }),
      signed(raw, "msg_7", { at: now() + 6 * 60 }),
    ])
      expect((await w.webhooks("POST", url, bad)).status).toBe(401);
    const stored = await db().select().from(webhookReceipts).where(eq(webhookReceipts.sourceId, sourceId));
    expect(stored.map((r) => r.eventKey).sort()).toEqual(["msg_1", "msg_2", "msg_3"]);
    expect(stored.find((r) => r.eventKey === "msg_1")!.request.headers).toMatchObject({
      "webhook-id": "msg_1",
      "webhook-signature": "[REDACTED]",
    });
    await w.witden.runtime.drain();
    expect((await receipts()).map((r) => r.status)).toEqual(["dispatched", "dispatched", "dispatched"]);
    // A source holding only the hash cannot check signatures; its token still works.
    await db().update(webhookSources).set({ secretEncrypted: null }).where(eq(webhookSources.id, sourceId));
    expect((await w.webhooks("POST", url, signed(raw, "msg_8"))).status).toBe(401);
    expect((await receive()).status).toBe(202);
  });

